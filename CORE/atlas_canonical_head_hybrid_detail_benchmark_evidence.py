    @classmethod
    def measurements(
        cls,
    ) -> tuple[
        AtlasCanonicalHeadHybridDetailMeasurementObservation,
        ...,
    ]:
        return cls._MEASUREMENTS

    @classmethod
    def measurement_for_view(
        cls,
        source_view_id: str,
    ) -> AtlasCanonicalHeadHybridDetailMeasurementObservation:
        normalized = str(
            source_view_id
        ).strip()

        for measurement in cls._MEASUREMENTS:
            if measurement.source_view_id == normalized:
                return measurement

        raise KeyError(
            normalized
        )

    @classmethod
    def view_count(
        cls,
    ) -> int:
        return len(
            cls._MEASUREMENTS
        )

    @classmethod
    def active_vertex_total(
        cls,
    ) -> int:
        return sum(
            measurement.active_vertex_count
            for measurement in cls._MEASUREMENTS
        )

    @classmethod
    def clipped_vertex_total(
        cls,
    ) -> int:
        return sum(
            measurement.clipped_vertex_count
            for measurement in cls._MEASUREMENTS
        )

    @classmethod
    def clipped_vertex_fraction(
        cls,
    ) -> float:
        active_total = cls.active_vertex_total()

        if active_total == 0:
            return 0.0

        return (
            cls.clipped_vertex_total()
            / active_total
        )

    @classmethod
    def connectivity_signature_count(
        cls,
    ) -> int:
        return len(
            {
                measurement.connectivity_signature
                for measurement in cls._MEASUREMENTS
            }
        )
